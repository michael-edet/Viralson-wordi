<script>
    (function() {
        const form = document.getElementById('advertiseForm');
        const statusEl = document.getElementById('advertiseFormStatus');
        const btn = document.getElementById('advSubmitBtn');

        function showAdvStatus(type, msg) {
            if (!statusEl) return;
            statusEl.className = 'form-status show ' + type;
            statusEl.innerHTML = (type === 'success' ? '<i class="fas fa-check-circle"></i>' : '<i class="fas fa-exclamation-circle"></i>') + '<span>' + msg + '</span>';
        }

        if (form) {
            form.addEventListener('submit', async function(e) {
                e.preventDefault();
                const name = document.getElementById('adv-name').value.trim();
                const email = document.getElementById('adv-email').value.trim();
                const subject = document.getElementById('adv-package').value;
                const phone = document.getElementById('adv-budget').value.trim();
                const message = document.getElementById('adv-message').value.trim();

                if (!name || !email || !subject || !message) {
                    showAdvStatus('error', 'Please fill in all required campaign fields.');
                    return;
                }
                if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
                    showAdvStatus('error', 'Please enter a valid work email address.');
                    return;
                }

                const orig = btn.innerHTML;
                btn.innerHTML = '<i class="fas fa-spinner fa-spin"></i> Sending Inquiry...';
                btn.disabled = true;

                try {
                    let res;
                    if (typeof window.viralsonData !== 'undefined' && window.viralsonData.ajaxUrl) {
                        const fd = new FormData();
                        fd.append('action', 'viralson_contact');
                        fd.append('nonce', window.viralsonData.contactNonce);
                        fd.append('name', name);
                        fd.append('email', email);
                        fd.append('phone', phone);
                        fd.append('subject', subject);
                        fd.append('message', message);
                        res = await fetch(window.viralsonData.ajaxUrl, { method: 'POST', body: fd });
                    } else {
                        res = await fetch('/api/contact', {
                            method: 'POST',
                            headers: { 'Content-Type': 'application/json' },
                            body: JSON.stringify({ name, email, phone, subject, message })
                        });
                    }
                    const data = await res.json();
                    if (res.ok && data.success) {
                        showAdvStatus('success', 'Thank you, ' + name + '! Your sponsorship inquiry has been routed to our partnerships desk (iamoffixial@gmail.com).');
                        form.reset();
                    } else {
                        showAdvStatus('error', (data && data.data && data.data.message) || data.error || 'Unable to submit right now. Please email iamoffixial@gmail.com.');
                    }
                } catch (err) {
                    showAdvStatus('success', 'Thank you, ' + name + '! Please also feel free to email your brief directly to iamoffixial@gmail.com for immediate turnaround.');
                    form.reset();
                } finally {
                    btn.innerHTML = orig;
                    btn.disabled = false;
                }
            });
        }
    })();
</script>
